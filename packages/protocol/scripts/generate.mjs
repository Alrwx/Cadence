// Generates ts/index.ts and go/events.go from schema/*.schema.json.
// Supports the JSON Schema subset the event schemas use: objects, strings (with enum), booleans, integers, arrays.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schema");
const HEADER = "Code generated by packages/protocol/scripts/generate.mjs. DO NOT EDIT.";

const pascal = (s) => s.split(/[._-]/).map((p) => p[0].toUpperCase() + p.slice(1)).join("");
const singular = (s) => (s.endsWith("s") ? s.slice(0, -1) : s);
const goField = (s) => pascal(s).replace(/Id$/, "ID").replace(/Ids$/, "IDs").replace(/Url$/, "URL");

const events = readdirSync(schemaDir)
  .filter((f) => f.endsWith(".schema.json") && f !== "envelope.schema.json")
  .map((f) => JSON.parse(readFileSync(join(schemaDir, f), "utf8")))
  .sort((a, b) => a.title.localeCompare(b.title));

// Collect named object types (top-level data + nested objects), depth-first so nested types come first.
function collect(name, schema, out) {
  const base = name.replace(/Data$/, "");
  for (const [prop, s] of Object.entries(schema.properties ?? {})) {
    const nested = typeName(base, prop, s);
    if (nested) collect(nested, s.type === "array" ? s.items : s, out);
  }
  out.push({ name, schema });
}

function typeName(parent, prop, s) {
  if (s.type === "object") return parent + pascal(prop);
  if (s.type === "array" && s.items.type === "object") return parent + pascal(singular(prop));
  return null;
}

// ---- TypeScript ----
function tsType(parent, prop, s) {
  const named = typeName(parent, prop, s);
  if (s.type === "object") return named;
  if (s.type === "array") return `${named ?? tsType(parent, prop, s.items)}[]`;
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  return { string: "string", boolean: "boolean", integer: "number", number: "number" }[s.type];
}

let ts = `// ${HEADER}\n\nexport const PROTOCOL_VERSION = 1;\n`;
for (const ev of events) {
  const types = [];
  collect(pascal(ev.title) + "Data", ev, types);
  for (const { name, schema } of types) {
    const req = new Set(schema.required ?? []);
    const fields = Object.entries(schema.properties ?? {}).map(
      ([p, s]) => `  ${p}${req.has(p) ? "" : "?"}: ${tsType(name.replace(/Data$/, ""), p, s)};`,
    );
    if (name.endsWith("Data")) ts += `\n/** ${ev.description} (${ev["x-direction"]}) */`;
    ts += fields.length ? `\nexport interface ${name} {\n${fields.join("\n")}\n}\n` : `\nexport type ${name} = Record<string, never>;\n`;
  }
}
ts += `\nexport const EVENT_TYPES = [\n${events.map((e) => `  ${JSON.stringify(e.title)},`).join("\n")}\n] as const;\n`;
ts += `\nexport type EventType = (typeof EVENT_TYPES)[number];\n`;
ts += `\nexport interface EventDataMap {\n${events.map((e) => `  ${JSON.stringify(e.title)}: ${pascal(e.title)}Data;`).join("\n")}\n}\n`;
ts += `
export interface Envelope<T extends EventType = EventType> {
  type: T;
  v: typeof PROTOCOL_VERSION;
  sessionId: string;
  turnId?: string;
  ts: number;
  data: EventDataMap[T];
}

/** Discriminated union of every event; narrow on \`type\`. */
export type CadenceEvent = { [K in EventType]: Envelope<K> }[EventType];

export function isEventType(type: string): type is EventType {
  return (EVENT_TYPES as readonly string[]).includes(type);
}
`;
writeFileSync(join(root, "ts", "index.ts"), ts);

// ---- Go ----
function goType(parent, prop, s, required) {
  const named = typeName(parent, prop, s);
  if (s.type === "object") return required ? named : `*${named}`;
  if (s.type === "array") return `[]${named ?? goType(parent, prop, s.items, true)}`;
  const base = { string: "string", boolean: "bool", integer: "int64", number: "float64" }[s.type];
  return required || s.type === "string" ? base : `*${base}`;
}

let go = `// ${HEADER}\n\npackage protocol\n\nimport "encoding/json"\n\nconst Version = 1\n`;
go += `
// Envelope wraps every JSON event. Decode Data with NewData(Type).
type Envelope struct {
	Type      string          \`json:"type"\`
	V         int             \`json:"v"\`
	SessionID string          \`json:"sessionId"\`
	TurnID    string          \`json:"turnId,omitempty"\`
	TS        int64           \`json:"ts"\`
	Data      json.RawMessage \`json:"data"\`
}
`;
go += `\nconst (\n${events.map((e) => `\tType${pascal(e.title)} = ${JSON.stringify(e.title)}`).join("\n")}\n)\n`;
for (const ev of events) {
  const types = [];
  collect(pascal(ev.title) + "Data", ev, types);
  for (const { name, schema } of types) {
    const req = new Set(schema.required ?? []);
    if (name.endsWith("Data")) go += `\n// ${name}: ${ev.description} (${ev["x-direction"]})`;
    const fields = Object.entries(schema.properties ?? {}).map(([p, s]) => {
      const tag = req.has(p) ? p : `${p},omitempty`;
      return `\t${goField(p)} ${goType(name.replace(/Data$/, ""), p, s, req.has(p))} \`json:"${tag}"\``;
    });
    go += `\ntype ${name} struct {\n${fields.join("\n")}${fields.length ? "\n" : ""}}\n`;
  }
}
go += `
// NewData returns a pointer to the zero data struct for an event type, or false for unknown types.
func NewData(eventType string) (any, bool) {
	switch eventType {
${events.map((e) => `\tcase Type${pascal(e.title)}:\n\t\treturn &${pascal(e.title)}Data{}, true`).join("\n")}
	}
	return nil, false
}
`;
writeFileSync(join(root, "go", "events.go"), go);
console.log(`generated ${events.length} events`);
